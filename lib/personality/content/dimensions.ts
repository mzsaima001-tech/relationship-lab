export function getDimensionReading(
  dim: PersonalityDimension,
  score: number
): DimensionReading {
  if (score >= 65) return DIMENSION_READINGS[dim].high;
  if (score <= 35) return DIMENSION_READINGS[dim].low;
  return DIMENSION_READINGS[dim].mid;
}

