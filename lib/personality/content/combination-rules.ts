/** 按优先级降序返回所有命中的规则 */
export function evaluateCombinationRules(
  scores: Record<PersonalityDimension, number>
): CombinationRule[] {
  return COMBINATION_RULES.filter((rule) => rule.match(scores)).sort(
    (a, b) => b.priority - a.priority
  );
}