/** 主极 + 副极组合生成原型文案 */
function buildComboCopy(primaryId: PoleId, secondaryId: PoleId | null, name: string): ArchetypeCopy {
  const p = POLE_COPY[primaryId];
  const s = secondaryId ? POLE_COPY[secondaryId] : null;
  const pShort = POLES[primaryId].short;
  const sShort = secondaryId ? POLES[secondaryId].short : null;

  const essence = s
    ? `你${p.trait}；同时，你${s.trait}。`
    : `你${p.trait}。`;
  const portrait = s
    ? `你的关系模式里有两条清晰的线索。一是${pShort}：你${p.trait}。${p.daily}。\n\n二是${sShort}：你${s.trait}。${s.daily}。这两条线索交织在一起，就构成了「${name}」的你在关系里的样子。`
    : `你最鲜明的特征是${pShort}：你${p.trait}。${p.daily}。这构成了「${name}」的你在关系里的基本样子。`;
  const recentTendency = s
    ? `最近，「${pShort}」和「${sShort}」这两面可能轮流主导着你的状态——留意哪一种正在被关系放大。`
    : `最近，「${pShort}」这一面可能在关系里被放大得格外明显。`;
  const gift = s ? `${p.gift}。${s.gift}。` : `${p.gift}。`;
  const blindSpot = s ? `${p.blind}。${s.blind}。` : `${p.blind}。`;

  return { essence, portrait, recentTendency, gift, blindSpot };
}

// 生成全部组合原型文案（跳过已手写的 11 个精品原型）
for (const [key, name] of Object.entries(COMBO_NAMES)) {
  if (ARCHETYPE_COPY[name]) continue;
  const [a, b] = key.split("+") as [PoleId, PoleId];
  ARCHETYPE_COPY[name] = buildComboCopy(a, b, name);
}
for (const [poleId, name] of Object.entries(SINGLE_NAMES)) {
  if (ARCHETYPE_COPY[name]) continue;
  ARCHETYPE_COPY[name] = buildComboCopy(poleId as PoleId, null, name);
}

