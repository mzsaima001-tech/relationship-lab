export type ScoreBand = "high" | "midHigh" | "mid" | "midLow" | "low";

export function bandOf(score: number): ScoreBand {
  if (score >= 75) return "high";
  if (score >= 55) return "midHigh";
  if (score >= 45) return "mid";
  if (score >= 25) return "midLow";
  return "low";
}

